def onboarding_checklist(anchors_path: str | Path, config_path: str | Path) -> list[str]:
    """What is still missing before this clip can be run end to end."""
    missing: list[str] = []
    config_path, anchors_path = Path(config_path), Path(anchors_path)
    if not config_path.exists():
        missing.append(f"config not written: {config_path}")
    if not anchors_path.exists():
        missing.append(f"anchors not labelled: {anchors_path}")
    return missing
