"""Take a new clip from an mp4 to a runnable configuration."""

from __future__ import annotations

import math
from pathlib import Path

__all__ = ["onboarding_checklist", "scaffold_config", "suggest_anchor_frames"]


def suggest_anchor_frames(frame_count: int, max_gap: int = 100) -> list[int]:
    """Evenly spaced anchor frames covering the clip, every gap <= ``max_gap``."""
    if frame_count < 2:
        raise ValueError(f"need at least 2 frames to place anchors, got {frame_count}")
    last = frame_count - 1
    n_gaps = max(1, math.ceil(last / max_gap))
    return [round(i * last / n_gaps) for i in range(n_gaps + 1)]


